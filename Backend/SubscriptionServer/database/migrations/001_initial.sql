CREATE TABLE IF NOT EXISTS games (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, game_key VARCHAR(100) COLLATE utf8mb4_bin NOT NULL UNIQUE,
 name VARCHAR(150) NOT NULL, active TINYINT NOT NULL DEFAULT 1, portal_configuration VARCHAR(100) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, game_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(100) NOT NULL, email VARCHAR(254) COLLATE utf8mb4_bin NOT NULL,
 phone VARCHAR(30) COLLATE utf8mb4_bin NOT NULL, password_hash VARCHAR(255) NOT NULL,
 verified TINYINT NOT NULL DEFAULT 0, active_session_id BIGINT UNSIGNED NULL, created_at BIGINT NOT NULL,
 UNIQUE KEY account_email(game_id,email), UNIQUE KEY account_phone(game_id,phone), FOREIGN KEY(game_id) REFERENCES games(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sessions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 token_hash CHAR(64) COLLATE ascii_bin NOT NULL UNIQUE, device_name VARCHAR(200) NOT NULL,
 created_at BIGINT NOT NULL, last_seen BIGINT NOT NULL, expires_at BIGINT NOT NULL, revoked TINYINT NOT NULL DEFAULT 0,
 FOREIGN KEY(user_id) REFERENCES users(id), KEY session_expiry(expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS session_actions (
 token_hash CHAR(64) COLLATE ascii_bin PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, session_id BIGINT UNSIGNED NOT NULL,
 expires_at BIGINT NOT NULL, consumed TINYINT NOT NULL DEFAULT 0, FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS verification_tokens (
 token_hash CHAR(64) COLLATE ascii_bin PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, expires_at BIGINT NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS mail_outbox (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, recipient VARCHAR(254) NOT NULL,
 body TEXT NOT NULL, attempts INT NOT NULL DEFAULT 0, available_at BIGINT NOT NULL, delivered_at BIGINT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS billing_handoffs (
 token_hash CHAR(64) COLLATE ascii_bin PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, session_id BIGINT UNSIGNED NOT NULL,
 action VARCHAR(10) NOT NULL, expires_at BIGINT NOT NULL, consumed TINYINT NOT NULL DEFAULT 0,
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS billing_customers (
 user_id BIGINT UNSIGNED PRIMARY KEY, customer_id VARCHAR(100) COLLATE ascii_bin NOT NULL UNIQUE,
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS plans (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, game_id BIGINT UNSIGNED NOT NULL, plan_key VARCHAR(80) NOT NULL,
 name VARCHAR(150) NOT NULL, description TEXT NOT NULL, price_id VARCHAR(100) COLLATE ascii_bin NOT NULL,
 display_price VARCHAR(150) NOT NULL, active TINYINT NOT NULL DEFAULT 1,
 UNIQUE KEY game_plan(game_id,plan_key), UNIQUE KEY game_price(game_id,price_id), FOREIGN KEY(game_id) REFERENCES games(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS subscriptions (
 subscription_id VARCHAR(100) COLLATE ascii_bin PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 price_id VARCHAR(100) NOT NULL, product_id VARCHAR(100) NOT NULL DEFAULT '', payment_method_id VARCHAR(100) NOT NULL DEFAULT '',
 status VARCHAR(30) NOT NULL, started_at BIGINT NOT NULL, period_end BIGINT NOT NULL,
 cancel_at_period_end TINYINT NOT NULL DEFAULT 0, canceled_at BIGINT NOT NULL DEFAULT 0, synced_at BIGINT NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id), KEY user_subscription(user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS subscription_sync (
 user_id BIGINT UNSIGNED PRIMARY KEY, synced_at BIGINT NOT NULL DEFAULT 0, FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS checkout_attempts (
 user_id BIGINT UNSIGNED PRIMARY KEY, attempt_key CHAR(32) NOT NULL, session_id VARCHAR(100) NULL,
 price_id VARCHAR(100) NOT NULL, return_url VARCHAR(1000) NOT NULL, expires_at BIGINT NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS webhook_events (
 event_id VARCHAR(100) COLLATE ascii_bin PRIMARY KEY, customer_id VARCHAR(100) NULL, event_type VARCHAR(120) NOT NULL,
 received_at BIGINT NOT NULL, processed_at BIGINT NULL, attempts INT NOT NULL DEFAULT 0, available_at BIGINT NOT NULL,
 last_error VARCHAR(100) NULL, KEY pending_events(processed_at,available_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS rate_limits (
 bucket CHAR(64) COLLATE ascii_bin PRIMARY KEY, started_at BIGINT NOT NULL, hits INT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
